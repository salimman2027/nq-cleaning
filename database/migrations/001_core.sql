-- NQ Cleaning core schema (Phase 1, part 1). SQL Server 2019+.
SET XACT_ABORT ON;
BEGIN TRAN;

CREATE TABLE Companies(
  Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(200) NOT NULL,
  Currency CHAR(3) NOT NULL DEFAULT 'SAR', TimeZone VARCHAR(50) NOT NULL DEFAULT 'Asia/Riyadh',
  VatRate DECIMAL(5,2) NOT NULL DEFAULT 15.00,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), IsDeleted BIT NOT NULL DEFAULT 0,
  RowVer ROWVERSION);

CREATE TABLE Branches(
  Id INT IDENTITY PRIMARY KEY, CompanyId INT NOT NULL REFERENCES Companies(Id),
  Name NVARCHAR(200) NOT NULL, City NVARCHAR(100) NULL,
  IsDeleted BIT NOT NULL DEFAULT 0, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT UQ_Branch UNIQUE(CompanyId, Name));

CREATE TABLE Roles(Id INT IDENTITY PRIMARY KEY, CompanyId INT NOT NULL REFERENCES Companies(Id), Name VARCHAR(60) NOT NULL, CONSTRAINT UQ_Role UNIQUE(CompanyId,Name));
CREATE TABLE Permissions(Id INT IDENTITY PRIMARY KEY, Code VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE RolePermissions(RoleId INT NOT NULL REFERENCES Roles(Id), PermissionId INT NOT NULL REFERENCES Permissions(Id), PRIMARY KEY(RoleId,PermissionId));

CREATE TABLE Users(
  Id INT IDENTITY PRIMARY KEY, CompanyId INT NOT NULL REFERENCES Companies(Id),
  BranchId INT NULL REFERENCES Branches(Id), FullName NVARCHAR(200) NOT NULL,
  Email NVARCHAR(256) NOT NULL, PasswordHash NVARCHAR(255) NOT NULL,
  IsActive BIT NOT NULL DEFAULT 1, IsDeleted BIT NOT NULL DEFAULT 0,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), CreatedBy INT NULL,
  UpdatedAt DATETIME2 NULL, UpdatedBy INT NULL, RowVer ROWVERSION,
  CONSTRAINT UQ_User_Email UNIQUE(CompanyId, Email));
CREATE TABLE UserRoles(UserId INT NOT NULL REFERENCES Users(Id), RoleId INT NOT NULL REFERENCES Roles(Id), PRIMARY KEY(UserId,RoleId));
CREATE TABLE RefreshTokens(
  Id BIGINT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id),
  TokenHash CHAR(64) NOT NULL UNIQUE, ExpiresAt DATETIME2 NOT NULL,
  RevokedAt DATETIME2 NULL, ReplacedBy BIGINT NULL);

CREATE TABLE Customers(
  Id INT IDENTITY PRIMARY KEY, CompanyId INT NOT NULL REFERENCES Companies(Id),
  Code VARCHAR(20) NOT NULL, Name NVARCHAR(200) NOT NULL,
  Type VARCHAR(10) NOT NULL CHECK (Type IN ('individual','company')),
  Mobile VARCHAR(20) NOT NULL, Whatsapp VARCHAR(20) NULL, Email NVARCHAR(256) NULL,
  VatNumber VARCHAR(20) NULL, Source NVARCHAR(100) NULL, Notes NVARCHAR(MAX) NULL,
  IsDeleted BIT NOT NULL DEFAULT 0, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), CreatedBy INT NULL,
  UpdatedAt DATETIME2 NULL, UpdatedBy INT NULL, RowVer ROWVERSION,
  CONSTRAINT UQ_Cust_Code UNIQUE(CompanyId, Code));
CREATE INDEX IX_Cust_Mobile ON Customers(CompanyId, Mobile);

CREATE TABLE CustomerAddresses(
  Id INT IDENTITY PRIMARY KEY, CustomerId INT NOT NULL REFERENCES Customers(Id),
  Label NVARCHAR(100) NULL, City NVARCHAR(100) NULL, District NVARCHAR(100) NULL,
  Street NVARCHAR(300) NULL, MapUrl NVARCHAR(500) NULL,
  Latitude DECIMAL(9,6) NULL, Longitude DECIMAL(9,6) NULL, IsDeleted BIT NOT NULL DEFAULT 0);

CREATE TABLE Services(
  Id INT IDENTITY PRIMARY KEY, CompanyId INT NOT NULL REFERENCES Companies(Id),
  Name NVARCHAR(200) NOT NULL, PricingMethod VARCHAR(20) NOT NULL,
  DefaultMinutes INT NOT NULL, DefaultTechnicians INT NOT NULL DEFAULT 1,
  IsActive BIT NOT NULL DEFAULT 1, IsDeleted BIT NOT NULL DEFAULT 0);
CREATE TABLE ServicePrices(
  Id INT IDENTITY PRIMARY KEY, ServiceId INT NOT NULL REFERENCES Services(Id),
  Price DECIMAL(18,2) NOT NULL, Unit VARCHAR(20) NOT NULL, Region NVARCHAR(100) NULL,
  CustomerType VARCHAR(10) NULL, ValidFrom DATE NOT NULL, ValidTo DATE NULL);

CREATE TABLE Technicians(
  Id INT IDENTITY PRIMARY KEY, CompanyId INT NOT NULL REFERENCES Companies(Id),
  BranchId INT NOT NULL REFERENCES Branches(Id), Code VARCHAR(20) NOT NULL,
  FullName NVARCHAR(200) NOT NULL, Mobile VARCHAR(20) NULL,
  HourlyCost DECIMAL(18,2) NOT NULL DEFAULT 0,
  Status VARCHAR(20) NOT NULL DEFAULT 'available',
  IsDeleted BIT NOT NULL DEFAULT 0, RowVer ROWVERSION,
  CONSTRAINT UQ_Tech_Code UNIQUE(CompanyId, Code));

CREATE TABLE Bookings(
  Id BIGINT IDENTITY PRIMARY KEY, CompanyId INT NOT NULL REFERENCES Companies(Id),
  BranchId INT NOT NULL REFERENCES Branches(Id), BookingNo VARCHAR(20) NOT NULL,
  CustomerId INT NOT NULL REFERENCES Customers(Id), AddressId INT NOT NULL REFERENCES CustomerAddresses(Id),
  StartAt DATETIME2 NOT NULL, EndAt DATETIME2 NOT NULL,
  Status VARCHAR(30) NOT NULL DEFAULT 'new',
  Subtotal DECIMAL(18,2) NOT NULL DEFAULT 0, Discount DECIMAL(18,2) NOT NULL DEFAULT 0,
  Vat DECIMAL(18,2) NOT NULL DEFAULT 0, Total DECIMAL(18,2) NOT NULL DEFAULT 0,
  Paid DECIMAL(18,2) NOT NULL DEFAULT 0, IdempotencyKey VARCHAR(64) NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), CreatedBy INT NULL,
  UpdatedAt DATETIME2 NULL, UpdatedBy INT NULL, IsDeleted BIT NOT NULL DEFAULT 0, RowVer ROWVERSION,
  CONSTRAINT UQ_BookingNo UNIQUE(CompanyId, BookingNo),
  CONSTRAINT CK_Booking_Time CHECK (EndAt > StartAt));
CREATE UNIQUE INDEX UX_Booking_Idem ON Bookings(CompanyId, IdempotencyKey) WHERE IdempotencyKey IS NOT NULL;

CREATE TABLE BookingDetails(
  Id BIGINT IDENTITY PRIMARY KEY, BookingId BIGINT NOT NULL REFERENCES Bookings(Id),
  ServiceId INT NOT NULL REFERENCES Services(Id), Quantity DECIMAL(10,2) NOT NULL,
  UnitPrice DECIMAL(18,2) NOT NULL, LineTotal DECIMAL(18,2) NOT NULL);

CREATE TABLE BookingAssignments(
  Id BIGINT IDENTITY PRIMARY KEY, BookingId BIGINT NOT NULL REFERENCES Bookings(Id),
  TechnicianId INT NOT NULL REFERENCES Technicians(Id),
  StartAt DATETIME2 NOT NULL, EndAt DATETIME2 NOT NULL, IsActive BIT NOT NULL DEFAULT 1,
  CONSTRAINT CK_Assign_Time CHECK (EndAt > StartAt));
CREATE INDEX IX_Assign_Tech_Time ON BookingAssignments(TechnicianId, StartAt, EndAt) WHERE IsActive = 1;

CREATE TABLE BookingStatusHistory(
  Id BIGINT IDENTITY PRIMARY KEY, BookingId BIGINT NOT NULL REFERENCES Bookings(Id),
  FromStatus VARCHAR(30) NULL, ToStatus VARCHAR(30) NOT NULL, Reason NVARCHAR(500) NULL,
  ChangedBy INT NOT NULL, ChangedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME());

CREATE TABLE AuditLogs(
  Id BIGINT IDENTITY PRIMARY KEY, CompanyId INT NULL, UserId INT NULL,
  Action VARCHAR(100) NOT NULL, Entity VARCHAR(100) NOT NULL, EntityId VARCHAR(50) NULL,
  Details NVARCHAR(MAX) NULL, At DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME());

CREATE TABLE SystemSettings(
  CompanyId INT NOT NULL REFERENCES Companies(Id), [Key] VARCHAR(100) NOT NULL,
  Value NVARCHAR(MAX) NULL, PRIMARY KEY(CompanyId,[Key]));

COMMIT;
